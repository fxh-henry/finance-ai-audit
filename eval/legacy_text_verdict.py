# -*- coding: utf-8 -*-
"""
冻结的旧版文本结论解析器（消融实验 D 组基线）
================================================================
为什么要把一段"已经过时"的代码原样冻在这里：

项目原来的做法是：让模型输出一段自然语言结论，程序再从这段文字里
用"关键词谁先出现"的方式猜结论。这个做法实测会猜错，典型反例：

    我通过调用费用标准工具核对后确认，该笔住宿费超标，审核不通过
    ↑ 位置 1                                    真正的结论在最后 ↑

"通过"出现在"不通过"之前 → 旧逻辑判成「通过」→ 一张超标发票被放行。

后来 utils/audit_verdict.py 已经把这段逻辑加固了（先遮罩否定词、再取最后出现位置）。
如果消融实验的 D 组直接调用加固后的函数，D 组会表现得和结构化方案差不多，
实验就会得出"结构化裁决提升 0%"的错误结论 —— 那是自证，不是测量。

所以这里保留一份改造前的实现，**只用于对照，不要修改**：
一旦修改，D 组就失去基线意义，整组数据作废。
================================================================
"""


def legacy_parse(text):
    """
    改造前的解析逻辑：在原始文本里找「通过」和「不通过」的首次出现位置，
    谁在前面就按谁算。

    已知缺陷（保留此缺陷正是本文件存在的意义）：
        1. 不做否定词遮罩 ——「不通过」内部的"通过"会被当成肯定结论；
        2. 比较的是"谁先出现"，而结论通常在文末，所以长句子里极易判反。

    参数：
        text: 模型输出的自然语言结论文本
    返回：
        "通过" / "不通过" / None（一个关键词都没找到）
    """
    if not text:  # 空文本或 None
        return None  # 判不出来

    pos_pass = text.find("通过")  # 「通过」第一次出现的位置（会把「不通过」里的"通过"也算进来）
    pos_fail = text.find("不通过")  # 「不通过」第一次出现的位置

    if pos_pass == -1 and pos_fail == -1:  # 两个关键词都没出现
        return None  # 判不出来

    if pos_fail == -1:  # 只出现了肯定写法
        return "通过"
    if pos_pass == -1:  # 只出现了否定写法
        return "不通过"

    # 缺陷所在：比的是"谁先出现"，而结论通常在文末
    return "通过" if pos_pass < pos_fail else "不通过"